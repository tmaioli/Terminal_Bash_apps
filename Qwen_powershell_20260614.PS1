# Query essential system information using CIM (equivalent to WMI)
$os = Get-CimInstance Win32_OperatingSystem
$cpu = Get-CimInstance Win32_Processor
$cs = Get-CimInstance Win32_ComputerSystem
$disk = Get-CimInstance Win32_LogicalDisk -Filter "DeviceID='C:'"

# Create a custom object to hold the collected information
$report = [PSCustomObject]@{
    ComputerName  = $cs.Name                # Name of the computer system
    Manufacturer  = $cs.Manufacturer         # Hardware manufacturer
    Model         = $cs.Model               # Hardware model
    OS            = $os.Caption             # Operating system name/version
    CPU           = $cpu.Name.Trim()       # CPU name/model
    Cores         = $cpu.NumberOfCores      # Number of CPU cores
    # Calculate total physical memory in GB (convert from KB via MB)
    RAM_Total_GB  = [math]::Round($os.TotalVisibleMemorySize / 1MB, 2)
    # Calculate free physical memory in GB (convert from KB via MB)
    RAM_Free_GB   = [math]::Round($os.FreePhysicalMemory / 1MB, 2)
    # Calculate free space on the C: drive in GB
    Disk_C_Free   = [math]::Round($disk.FreeSpace / 1GB, 2)
    # Calculate uptime by subtracting the last boot time from the current time
    Uptime        = (Get-Date) - $os.LastBootUpTime
}

# Display the collected information as a clean, formatted list
$report | Format-List

